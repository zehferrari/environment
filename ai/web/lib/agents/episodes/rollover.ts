// ENV-121 (second review) — the rollover SEAL.
//
// The first review round gave the barrier its fence: a message that spent its
// episode budget can no longer mutate the task. That closed the "one stable
// conversation spans arbitrarily many nominal episodes" hole, but it left the
// other half of the boundary open.
//
// The hole this module closes: tool-budget exhaustion armed the successor
// continuation IMMEDIATELY, at the moment the `tool:call` landed. So episode
// N+1 was scheduled while episode N's checkpoint did not exist yet — and, since
// nothing in the stream path can interrupt a model mid-turn, the fenced message
// is never told it was fenced and may simply finish without ever calling
// `checkpoint`. The successor would then be dispatched and briefed from a
// checkpoint that was never written: exactly the lossy handover episodes exist
// to replace.
//
// The rule here is therefore: NO SUCCESSOR DISPATCH BEFORE N'S CHECKPOINT IS
// DURABLE. Rollover raises the barrier and opens the successor row, and that is
// all. The continuation that actually schedules N+1 is armed only by a
// successful SEAL, which is one of exactly two things:
//
//   1. the fenced turn's own final `action=checkpoint` (preferred — the agent's
//      own words), or
//   2. a deterministic PM-generated checkpoint written when that turn ends, or
//      when the sweeper finds a barrier whose turn died without ending cleanly.
//
// Both paths go through `releaseEpisodeRolloverBarrier`, whose conditional
// atomic update makes the seal single-use under concurrency, so the two paths
// racing each other cannot double-arm or overwrite the agent's checkpoint.

import { db } from "@/lib/db";
import {
  findUnsealedEpisodeRolloverBarriers,
  releaseEpisodeRolloverBarrier,
  resolveEpisodeRolloverBarrier,
  serverGeneratedEpisodeCheckpoint,
  type EpisodeCheckpoint,
  type TaskExecutionEpisodeSummary,
} from "@/lib/agents/episodes/lifecycle";
import { armPmChannelContinuations } from "@/lib/agents/pm-channel/continuations";

export const EPISODE_SEAL_REASON = {
  agentCheckpoint: "agent_checkpoint",
  turnEnded: "turn_ended_without_checkpoint",
  turnAbandoned: "turn_abandoned_without_checkpoint",
} as const;

/** The continuation action name a sealed rollover schedules the successor under. */
export const EPISODE_ROLLOVER_CONTINUATION_ACTION = "episode_rollover";

/** Runs that are still capable of producing more events. */
const LIVE_RUN_STATUSES = ["queued", "accepted", "streaming", "retryable"] as const;

/** How long a raised-but-unsealed barrier may sit before the sweeper seals it. */
const SWEEP_GRACE_MS = 5 * 60_000;

export interface EpisodeSealOutcome {
  /** The closed episode whose barrier was consumed, with the sealed checkpoint. */
  episode: TaskExecutionEpisodeSummary;
  /** True when the seal scheduled the successor episode's turn. */
  successorScheduled: boolean;
  /** Whether the checkpoint came from the agent or was generated by PM. */
  reason: string;
}

/**
 * Arm the continuation that will dispatch the successor episode.
 *
 * Status matters. A continuation is `armed` while its turn is still running and
 * only becomes drainable (`queued`) when the run settles — that is ENV-118's
 * "the agent called start and then went quiet" recovery. If the fenced run has
 * ALREADY settled by the time we seal, there is no settle left to promote the
 * row, so it must be queued directly or the successor would wait forever.
 */
async function scheduleSuccessorEpisode(args: {
  taskId: string;
  agentSlug: string;
  messageId: string;
}): Promise<boolean> {
  const run = await db.pmChannelRun.findFirst({
    where: { taskId: args.taskId, agentSlug: args.agentSlug, messageId: args.messageId },
    orderBy: { createdAt: "desc" },
    select: { id: true, projectId: true, taskId: true, epicId: true, status: true },
  });
  if (!run?.taskId) return false;
  const runIsLive = (LIVE_RUN_STATUSES as readonly string[]).includes(run.status);
  await db.$transaction((tx) =>
    armPmChannelContinuations(tx, {
      runs: [run],
      agentSlug: args.agentSlug,
      messageId: args.messageId,
      action: EPISODE_ROLLOVER_CONTINUATION_ACTION,
      now: new Date(),
      status: runIsLive ? "armed" : "queued",
    }),
  );
  return true;
}

/**
 * Consume the barrier raised against `messageId` and, only then, schedule the
 * successor episode.
 *
 * Returns null when there is no barrier for this message, or when another
 * request consumed it first. A null is not an error at the call sites that seal
 * opportunistically (turn end, sweeper); the workflow route turns it into the
 * 409 that keeps "exactly one final checkpoint" true.
 */
export async function sealEpisodeRolloverBarrier(args: {
  taskId: string;
  agentSlug: string;
  messageId: string;
  /** The agent's own checkpoint. Omit to have PM derive one. */
  checkpoint?: EpisodeCheckpoint | null;
  reason: string;
}): Promise<EpisodeSealOutcome | null> {
  const barrier = await resolveEpisodeRolloverBarrier({
    taskId: args.taskId,
    agentSlug: args.agentSlug,
    messageId: args.messageId,
  });
  if (!barrier || barrier.state === "consumed") return null;

  const checkpoint =
    args.checkpoint ?? serverGeneratedEpisodeCheckpoint(barrier.episode, args.reason);
  const sealed = await db.$transaction((tx) =>
    releaseEpisodeRolloverBarrier(tx, { episodeId: barrier.episode.id, checkpoint }),
  );
  // Lost the race. The winner's checkpoint stands and the winner already
  // scheduled the successor; doing either again here would overwrite the
  // agent's words or arm a second turn in the same lane (WFI-001).
  if (!sealed) return null;

  const successorScheduled = await scheduleSuccessorEpisode({
    taskId: args.taskId,
    agentSlug: args.agentSlug,
    messageId: args.messageId,
  });
  return { episode: sealed, successorScheduled, reason: args.reason };
}

/**
 * Best-effort seal for a turn that is ending. Never throws: a stream callback
 * must not fail because episode bookkeeping did.
 */
export async function sealEpisodeRolloverBarrierOnTurnEnd(args: {
  taskId: string;
  agentSlug: string;
  messageId: string;
}): Promise<EpisodeSealOutcome | null> {
  try {
    return await sealEpisodeRolloverBarrier({ ...args, reason: EPISODE_SEAL_REASON.turnEnded });
  } catch (err) {
    console.warn("[pm-channel] failed to seal execution episode rollover barrier", err);
    return null;
  }
}

/**
 * Safety net for turns that never end cleanly.
 *
 * A crashed gateway, a killed process or a dropped stream leaves the barrier
 * raised and unsealed, which under the gating rule above means the successor is
 * never scheduled. The sweeper is what keeps "gate the dispatch" from turning a
 * rollover into a permanent stall: after a grace period it writes the derived
 * checkpoint itself and lets the successor go.
 *
 * Runs alongside the continuation drain in the PM channel worker.
 */
export async function sweepUnsealedEpisodeRolloverBarriers(args: {
  now?: Date;
  graceMs?: number;
  limit?: number;
} = {}) {
  const now = args.now ?? new Date();
  const olderThan = new Date(now.getTime() - (args.graceMs ?? SWEEP_GRACE_MS));
  const stalled = await findUnsealedEpisodeRolloverBarriers({ olderThan, take: args.limit ?? 20 });
  let sealed = 0;
  let scheduled = 0;
  for (const episode of stalled) {
    if (!episode.exhaustedByMessageId) continue;
    // A run that is still producing events has not abandoned anything yet; the
    // fenced turn may be seconds away from writing its own checkpoint, and the
    // agent's words always beat PM's derivation.
    const liveRun = await db.pmChannelRun.findFirst({
      where: {
        taskId: episode.taskId,
        agentSlug: episode.agentSlug,
        messageId: episode.exhaustedByMessageId,
        status: { in: [...LIVE_RUN_STATUSES] },
      },
      select: { id: true },
    });
    if (liveRun) continue;
    const outcome = await sealEpisodeRolloverBarrier({
      taskId: episode.taskId,
      agentSlug: episode.agentSlug,
      messageId: episode.exhaustedByMessageId,
      reason: EPISODE_SEAL_REASON.turnAbandoned,
    }).catch((err) => {
      console.warn("[pm-channel] failed to sweep execution episode rollover barrier", err);
      return null;
    });
    if (!outcome) continue;
    sealed += 1;
    if (outcome.successorScheduled) scheduled += 1;
  }
  return { sealed, scheduled };
}
