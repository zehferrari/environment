import { runRouteHandler } from './lib/next-route-harness';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { projectThinking, redactThinkingText } from '@/lib/tasks/thinking/projection';
import { taskDetailTabsForRole } from '@/lib/auth/roles';

async function main() {
  const dir = mkdtempSync(path.join(tmpdir(), 'pm-thinking-'));
  Object.assign(process.env, { DATABASE_URL: `file:${dir}/test.db`, AUTH_SECRET: 'thinking-fixture', PM_ASYNC_DISPATCH_INLINE_NUDGE: '0' });
  await promisify(execFile)('pnpm', ['prisma', 'migrate', 'deploy'], { env: process.env });
  const { db } = await import('@/lib/db');
  try {
    const { persistTaskReply } = await import('@/lib/agents/pm-channel/persist-task-reply');
    const { pmChannelTargetHasDurableReply, pmChannelRunTargetKey } = await import('@/lib/agents/pm-channel/runs');
    const { appendPmChannelStreamEventForTarget } = await import('@/lib/agents/pm-channel/stream-log');
    const { publishTaskNote } = await import('@/lib/tasks/thinking/notes');
    const { taskThinkingResponse } = await import('@/lib/tasks/thinking/read');
    const { createTaskWorkflowToken } = await import('@/lib/agents/workflow/token/task');
    const { compactHttpContract } = await import('@/lib/agents/pm-channel/task-runtime');
    const owner = await db.user.create({ data: { username: 'owner', email: 'owner@thinking.invalid', kind: 'human', isOwner: true } });
    const agent = await db.agent.create({ data: { slug: 'thinker', name: 'Thinker', role: 'coding' } });
    const user = await db.user.create({ data: { username: 'thinker', email: 'agent@thinking.invalid', kind: 'agent', agentId: agent.id } });
    const project = await db.project.create({ data: { name: 'Thinking test', slug: 'thinking-test' } });
    const task = await db.task.create({ data: { projectId: project.id, title: 'Test task', status: 'In Progress', assigneeId: user.id, reporterId: owner.id } });
    const makeTurn = async (provider: string, autonomous = true, dedupe = true) => {
      await db.pmChannelRun.updateMany({ where: { taskId: task.id }, data: { status: 'completed' } });
      const origin = autonomous ? null : await db.comment.create({ data: { taskId: task.id, userId: owner.id, body: 'What did you find?' } });
      const message = await db.agentChatMessage.create({ data: { taskId: task.id, projectId: project.id, agentSlug: agent.slug, senderUserId: owner.id, body: 'Continue', originChannel: 'comment', originCommentId: origin?.id ?? null, ...(autonomous && dedupe ? { workflowDedupeKey: `thinking-${provider}-${Date.now()}` } : {}) } });
      const target = { kind: 'task-comment' as const, taskId: task.id, messageId: message.id, agentSlug: agent.slug };
      const run = await db.pmChannelRun.create({ data: { targetKey: pmChannelRunTargetKey(target), kind: target.kind, messageId: message.id, taskId: task.id, agentSlug: agent.slug, provider, model: 'fixture', status: 'streaming' } });
      return { target, run, message, token: createTaskWorkflowToken(message.id, task.id, agent.slug) };
    };
    for (const provider of ['openai', 'anthropic', 'ollama']) {
      const turn = await makeTurn(provider);
      const note = { messageId: turn.message.id, token: turn.token, category: 'finding', body: 'The source logs cover the requested period.' };
      const before = await db.comment.count({ where: { taskId: task.id } });
      const notes = await Promise.all([publishTaskNote(task.id, note), publishTaskNote(task.id, note)]);
      assert.deepEqual(notes.map(r => r.status).sort(), [200, 201]);
      assert.equal(await db.comment.count({ where: { taskId: task.id } }), before + 1);
      assert.equal((await publishTaskNote('wrong-task', note)).status, 404);
      assert.equal((await publishTaskNote(task.id, { ...note, token: 'wrong' })).status, 403);
      assert.equal((await publishTaskNote(task.id, { ...note, body: 'x'.repeat(2001) })).status, 400);
      assert.equal((await publishTaskNote(task.id, { ...note, category: 'progress' })).status, 400);
      assert.equal(await pmChannelTargetHasDurableReply(turn.target), false, 'an explicit note does not settle the turn');
      await appendPmChannelStreamEventForTarget({ target: turn.target, event: 'partial', text: 'Checking existing files.', replace: true });
      await appendPmChannelStreamEventForTarget({ target: turn.target, event: 'reasoning', text: 'Compare the observed coverage before drawing conclusions.' });
      await appendPmChannelStreamEventForTarget({ target: turn.target, event: 'tool:start', toolName: 'read_file', toolCallId: 'call-one' });
      await appendPmChannelStreamEventForTarget({ target: turn.target, event: 'tool:start', toolName: 'read_file', toolCallId: 'call-one' });
      await appendPmChannelStreamEventForTarget({ target: turn.target, event: 'final', text: 'Now rendering the report.', replace: true });
      const count = await db.comment.count();
      const result = await runRouteHandler(() => persistTaskReply(turn.target, `Now rendering the report. token=${turn.token}`));
      assert.equal(result.status, 200); assert.ok('thinkingOnly' in result.body && result.body.thinkingOnly);
      assert.equal(await db.comment.count(), count, 'autonomous narration must not create comments');
      assert.equal(await pmChannelTargetHasDurableReply(turn.target), true, 'durable narration receipt prevents false no-reply retries');
      const stored = await db.taskThinkingSnapshot.findUniqueOrThrow({ where: { runId: turn.run.id } });
      assert.match(stored.progress, /Checking existing files/);
      assert.match(stored.progress, /rendering/);
      assert.ok(!stored.progress.includes(turn.token));
      assert.match(stored.reasoning, /observed coverage/);
      assert.equal(JSON.parse(stored.tools).length, 1);
      assert.equal(await db.pmChannelStreamEvent.count({ where: { runId: turn.run.id } }), 1, 'stream compaction still works; Thinking retains independent history');
      await db.pmChannelRun.update({ where: { id: turn.run.id }, data: { status: 'completed' } });
      assert.equal((await publishTaskNote(task.id, note)).status, 200, 'identical note replay remains idempotent');
      assert.equal((await publishTaskNote(task.id, { ...note, body: 'A different late note' })).status, 409);
    }
    const noDedupe = await makeTurn('no-dedupe', true, false);
    await db.activityLog.create({ data: { projectId: project.id, taskId: task.id, userId: owner.id, targetAgent: agent.slug, kind: 'task.workflow.notify', payload: JSON.stringify({ messageId: noDedupe.message.id, reason: 'monitor_recovery' }) } });
    const count = await db.comment.count();
    await runRouteHandler(() => persistTaskReply(noDedupe.target, 'Resuming the checkpoint.'));
    assert.equal(await db.comment.count(), count, 'workflow wakes without optional dedupe keys also route to Thinking');
    const human = await makeTurn('human-question', false);
    await runRouteHandler(() => persistTaskReply(human.target, 'The logs cover July through September.'));
    assert.equal(await db.comment.count({ where: { runId: human.run.id } }), 1, 'direct human question still gets a comment answer');
    assert.equal(await db.pmChannelJob.count(), 0, 'notes and Thinking reads do not wake agents');
    const viewer = { id: owner.id, username: owner.username, kind: 'human' as const, role: 'owner' as const, agentVisibility: 'full' as const, canAccessOwnerFeatures: true };
    const req = new Request('http://localhost/api/tasks/x/thinking');
    assert.equal((await taskThinkingResponse(req, task.id, null)).status, 401);
    assert.equal((await taskThinkingResponse(req, task.id, { ...viewer, role: 'customer', canAccessOwnerFeatures: false, agentVisibility: 'hidden' })).status, 404);
    assert.equal((await taskThinkingResponse(req, task.id, { ...viewer, role: 'admin', canAccessOwnerFeatures: false, agentVisibility: 'masked' })).status, 404);
    assert.equal((await taskThinkingResponse(req, 'missing', viewer)).status, 404);
    for (let i = 0; i < 9; i++) await makeTurn(`page-${i}`);
    const page = await (await taskThinkingResponse(req, task.id, viewer)).json();
    assert.equal(page.runs.length, 10); assert.ok(page.nextCursor);
    const older = await (await taskThinkingResponse(new Request(`${req.url}?before=${page.nextCursor}`), task.id, viewer)).json();
    assert.ok(older.runs.length); assert.ok(older.runs.every((r: { id: string }) => !page.runs.some((p: { id: string }) => r.id === p.id)));
    assert.ok(!JSON.stringify(page).includes('sessionKey')); assert.equal(await db.pmChannelJob.count(), 0);
    const contract = compactHttpContract({ version: 1, taskId: task.id, messageId: human.message.id, agentSlug: agent.slug, token: human.token, contextUrl: `http://127.0.0.1:3000/api/agents/context/task/${task.id}?grant=fixture`, workflowUrl: `http://127.0.0.1:3000/api/agent/tasks/${task.id}/workflow`, actions: ['context', 'task_note'] });
    assert.match(contract, /\/notes/); assert.match(contract, /Thinking/);
    assert.ok(taskDetailTabsForRole('owner', true).includes('Thinking'));
    for (const role of ['admin', 'customer', null] as const) assert.ok(!taskDetailTabsForRole(role, true).includes('Thinking'));
    let state = { progress: '', reasoning: '', tools: '[]', truncated: false };
    state = projectThinking(state, { event: 'partial', delta: 'x'.repeat(17000) }, 1);
    assert.equal(state.progress.length, 16000); assert.equal(state.truncated, true);
    assert.equal(redactThinkingText('Bearer abc123 https://local?grant=secret&x=1 token="hidden"'), 'Bearer [redacted] https://local?grant=[redacted]&x=1 token=[redacted]');
    console.log('PASS provider-neutral routing, explicit note authorization/replay, human answers, durable compacted history, redaction, pagination and owner-only access');
  } finally { await db.$disconnect(); rmSync(dir, { recursive: true, force: true }); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
