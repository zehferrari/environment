import assert from "node:assert/strict";
import { uploadPmTaskAttachment } from "../openclaw-pm-channel/task-attachments.js";
const turn = { replyTarget: { kind: "task-comment", taskId: "t", messageId: "m" }, taskRuntime: { taskId: "t", messageId: "m", token: "secret", workflowUrl: "http://127.0.0.1:3000/api/agent/tasks/t/workflow" } };
let current = turn;
let calls = 0;
const args = { turn, findTurn: () => current, mediaUrl: "file.csv", loadMedia: async () => ({ buffer: Buffer.from("order,value\n1,0.1\n"), fileName: "audit.csv", contentType: "text/csv" }), fetchImpl: async (url, request) => {
  calls++;
  assert.equal(url, "http://127.0.0.1:3000/api/agent/tasks/t/attachments");
  assert.equal(request.body.get("token"), "secret");
  assert.equal(request.body.get("messageId"), "m");
  assert.equal(request.body.get("file").name, "audit.csv");
  assert.equal(await request.body.get("file").text(), "order,value\n1,0.1\n");
  return Response.json({ attachment: { id: "saved" } }, { status: 201 });
} };
assert.deepEqual(await uploadPmTaskAttachment(args), { id: "saved", filename: "audit.csv", downloadUrl: "/api/attachments/saved" });
assert.equal(calls, 1);
current = null;
await assert.rejects(uploadPmTaskAttachment(args), /no longer active/);
current = turn;
await assert.rejects(uploadPmTaskAttachment({ ...args, loadMedia: async () => { current = null; return { buffer: Buffer.from("x") }; } }), /no longer active/);
assert.equal(calls, 1, "a replaced generation cannot upload after its file read");
current = turn;
await assert.rejects(uploadPmTaskAttachment({ ...args, fetchImpl: async () => Response.json({ error: "denied" }, { status: 403 }) }), /HTTP 403/);
await assert.rejects(uploadPmTaskAttachment({ ...args, loadMedia: async () => ({ buffer: Buffer.alloc(10 * 1024 * 1024 + 1) }) }), /at most 10 MiB/);
turn.taskRuntime.workflowUrl = "https://example.com/api/agent/tasks/t/workflow";
await assert.rejects(uploadPmTaskAttachment(args), /Invalid PM attachment endpoint/);
turn.taskRuntime.workflowUrl = "http://127.0.0.1:3000/api/agent/tasks/t/workflow";
turn.completedAction = "ready_for_review";
await assert.rejects(uploadPmTaskAttachment(args), /no longer active/);
console.log("PASS: attachment bytes, task grant, generation fencing, explicit upload failure, size limit and local endpoint policy");

// Both task surfaces share the native upload tool; no credential enters its schema.
const { createTaskTools } = await import('../openclaw-pm-channel/task-tools.js');
delete turn.completedAction;
turn.replyTarget.kind = 'task-chat';
turn.replyTarget.agentSlug = 'worker';
Object.assign(turn.taskRuntime, { version: 1, agentSlug: 'worker', actions: ['attach_file'], contextUrl: 'http://127.0.0.1:3000/api/agents/context/task/t?grant=private' });
turn.acceptedId = 'generation-1';
const [upload] = createTaskTools({ context: { messageChannel: 'pm', sessionKey: 's' }, findTurn: () => current, loadMedia: args.loadMedia, fetchImpl: args.fetchImpl });
const saved = await upload.execute('upload-1', { path: '/workspace/audit.csv' });
assert.equal(JSON.parse(saved.content[0].text).attachment.id, 'saved');
assert.equal(turn.completedAction, undefined, 'upload does not finish implementation');
await assert.rejects(upload.execute('upload-2', { path: '/workspace/audit.csv', token: 'injected' }), /Invalid PM tool arguments/);
await assert.rejects(upload.execute('upload-3', { path: 'https://example.com/file' }), /absolute path/);
current = null;
await assert.rejects(upload.execute('upload-4', { path: '/workspace/audit.csv' }), /replaced/);
console.log('PASS native attachment tool on task-chat: scoped upload, safe arguments and generation fence');
