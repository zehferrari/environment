import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtemp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
const exec = promisify(execFile);
async function main() {
    const root = await mkdtemp(path.join(tmpdir(), 'standalone-checkpoint-'));
    process.env.DATABASE_URL = `file:${root}/test.db`;
    process.env.PM_EPIC_MERGE_DIR = `${root}/spool`;
    process.env.PM_ASYNC_DISPATCH = '1';
    process.env.PM_ASYNC_DISPATCH_INLINE_NUDGE = '0';
    process.env.AUTH_SECRET = 'standalone-checkpoint-isolated-test-secret';
    await exec('pnpm', ['prisma', 'migrate', 'deploy'], { env: process.env });
    const { db } = await import('@/lib/db');
    try {
        const { publishStandaloneTaskCheckpoint } = await import('@/lib/deploy/epic-merge-git');
        const { runEpicMergeSpoolJob } = await import('@/lib/deploy/epic-merge');
        const { submitWorkflowCommand } = await import('@/lib/tasks/orchestrator');
        const { openTaskWorkflowCycle } = await import('@/lib/tasks/workflow-cycle');
        const { applyBlockerPermissionGrant } = await import('@/lib/tasks/blocker-permission-grant');
        const { taskToolActions } = await import('@/lib/agents/pm-channel/task-runtime');
        const repo = `${root}/repo`, origin = `${root}/origin.git`;
        const git = async (cwd: string, ...args: string[]) => (await exec('git', ['-C', cwd, ...args])).stdout.trim();
        await exec('git', ['init', '--bare', '-b', 'main', origin]);
        await exec('git', ['clone', origin, repo]);
        await git(repo, 'config', 'user.name', 'Test');
        await git(repo, 'config', 'user.email', 'test@checkpoint.invalid');
        await writeFile(`${repo}/base.txt`, 'original\n');
        await git(repo, 'add', '.');
        await git(repo, 'commit', '-m', 'base');
        await git(repo, 'push', 'origin', 'main');
        const base = await git(repo, 'rev-parse', 'HEAD');
        const fixture = async (name: string) => { const wt = `${repo}.worktrees/${name}`; await git(repo, 'worktree', 'add', '-b', name, wt, 'main'); await git(wt, 'push', 'origin', name); return wt; };
        const args = (wt: string, branch: string, auth: string) => ({ repoPath: repo, worktreePath: wt, taskBranch: branch, baseBranch: 'main', gitUserName: 'Test', gitUserEmail: 'test@checkpoint.invalid', commitSubject: 'TEST preview checkpoint', authorizationCommentId: auth });
        const wt = await fixture('feature-checkpoint');
        await writeFile(`${wt}/new.txt`, 'preview\n');
        const first = await publishStandaloneTaskCheckpoint(args(wt, 'feature-checkpoint', 'grant-one'));
        assert.ok(first.ok, JSON.stringify(first));
        assert.equal(await git(wt, 'status', '--porcelain'), '');
        assert.equal((await git(repo, 'ls-remote', 'origin', 'refs/heads/feature-checkpoint')).split(/\s/)[0], first.publishedSha);
        assert.equal(await git(repo, 'rev-parse', 'main'), base, 'integration branch untouched');
        await writeFile(`${wt}/later.txt`, 'newer work\n');
        const replay = await publishStandaloneTaskCheckpoint(args(wt, 'feature-checkpoint', 'grant-one'));
        assert.ok(replay.ok && replay.kind === 'already');
        assert.equal(await readFile(`${wt}/later.txt`, 'utf8'), 'newer work\n');
        assert.match(await git(wt, 'status', '--porcelain'), /later.txt/);
        const second = await publishStandaloneTaskCheckpoint(args(wt, 'feature-checkpoint', 'grant-two'));
        assert.ok(second.ok);
        assert.notEqual(second.publishedSha, first.publishedSha);
        assert.equal((await publishStandaloneTaskCheckpoint(args(repo, 'main', 'grant-main'))).ok, false);
        const child = await fixture('epic-child');
        await git(repo, 'config', 'branch.epic-child.pmEpicBranch', 'epic');
        await writeFile(`${child}/child.txt`, 'stay local\n');
        assert.equal((await publishStandaloneTaskCheckpoint(args(child, 'epic-child', 'grant-child'))).ok, false);
        assert.equal(await git(child, 'rev-parse', 'HEAD'), base);
        const stale = await fixture('stale');
        const elsewhere = `${root}/elsewhere`;
        await exec('git', ['clone', '-b', 'stale', origin, elsewhere]);
        await git(elsewhere, 'config', 'user.name', 'Other');
        await git(elsewhere, 'config', 'user.email', 'other@checkpoint.invalid');
        await writeFile(`${elsewhere}/remote.txt`, 'other change\n');
        await git(elsewhere, 'add', '.');
        await git(elsewhere, 'commit', '-m', 'remote advanced');
        await git(elsewhere, 'push', 'origin', 'stale');
        await writeFile(`${stale}/local.txt`, 'keep\n');
        assert.equal((await publishStandaloneTaskCheckpoint(args(stale, 'stale', 'grant-stale'))).ok, false);
        assert.equal(await git(stale, 'rev-parse', 'HEAD'), base, 'divergence refused before committing');
        const retryWt = await fixture('push-retry');
        await writeFile(`${retryWt}/pending.txt`, 'authorized change\n');
        const hook = `${origin}/hooks/pre-receive`;
        await writeFile(hook, '#!/bin/sh\nexit 1\n', { mode: 0o755 });
        const refused = await publishStandaloneTaskCheckpoint(args(retryWt, 'push-retry', 'grant-retry'));
        assert.equal(refused.ok, false, 'push refusal reported');
        const retainedSha = await git(retryWt, 'rev-parse', 'HEAD');
        assert.notEqual(retainedSha, base, 'failed push preserves checkpoint commit');
        await writeFile(`${retryWt}/later.txt`, 'not in original grant\n');
        assert.equal((await publishStandaloneTaskCheckpoint(args(retryWt, 'push-retry', 'grant-retry'))).ok, false, 'retry refuses later dirty work under consumed grant');
        assert.equal(await git(retryWt, 'rev-parse', 'HEAD'), retainedSha);
        await rm(`${retryWt}/later.txt`);
        await rm(hook);
        const recovered = await publishStandaloneTaskCheckpoint(args(retryWt, 'push-retry', 'grant-retry'));
        assert.ok(recovered.ok);
        assert.equal(recovered.publishedSha, retainedSha, 'clean retry pushes original checkpoint without another commit');
        assert.equal((await publishStandaloneTaskCheckpoint(args(repo, 'feature-checkpoint', 'grant-primary'))).ok, false, 'primary checkout rejected');
        const owner = await db.user.create({ data: { username: 'owner', email: 'owner@checkpoint.invalid', kind: 'human', isOwner: true } });
        const workerAgent = await db.agent.create({ data: { slug: 'worker', name: 'Worker', role: 'coding' } });
        const worker = await db.user.create({ data: { username: 'worker', email: 'worker@checkpoint.invalid', kind: 'agent', agentId: workerAgent.id } });
        const monitorAgent = await db.agent.create({ data: { slug: 'monitor', name: 'Monitor', role: 'monitor' } });
        await db.user.create({ data: { username: 'monitor', email: 'monitor@checkpoint.invalid', kind: 'agent', agentId: monitorAgent.id } });
        const project = await db.project.create({ data: { slug: 'checkpoints', name: 'Checkpoints', workMode: 'code', repositoryPath: repo, defaultGitUserName: 'Test', defaultGitUserEmail: 'test@checkpoint.invalid', deploymentProductionBranch: 'main' } });
        const liveWt = await fixture('integration');
        await writeFile(`${liveWt}/fix.txt`, 'needs live verification\n');
        const task = await db.task.create({ data: { projectId: project.id, title: 'Standalone browser verification', workItemKey: 'CHK-1', branchName: 'integration', status: 'In Progress', assigneeId: worker.id, reporterId: owner.id, approvedOn: new Date(), approvedById: owner.id } });
        const cycle = await db.$transaction(tx => openTaskWorkflowCycle(tx, { taskId: task.id, openedWorkflowVersion: 0 }));
        assert.ok(cycle);
        await db.taskRepositoryRun.create({ data: { taskId: task.id, workflowCycleId: cycle.id, repositoryPath: repo, worktreePath: liveWt, branchName: 'integration', baseSha: base, phase: 'active' } });
        await db.subTask.create({ data: { taskId: task.id, text: 'Browser/save/reload verification still open' } });
        const actor = { id: worker.id, kind: 'agent' as const, username: worker.username, role: 'assignee' as const, codingCapability: true };
        const command = async (intent: 'raise_blocker' | 'publish_checkpoint', payload: Record<string, unknown>, key: string) => submitWorkflowCommand({ taskId: task.id, intent, actor, source: 'agent', expectedWorkflowVersion: (await db.task.findUniqueOrThrow({ where: { id: task.id } })).workflowVersion, workflowCycleId: cycle.id, idempotencyKey: key, payload } as Parameters<typeof submitWorkflowCommand>[0]);
        const raise = await command('raise_blocker', { permissionKind: 'publish_checkpoint', permissionScope: 'Publish CHK-1 for browser verification', comment: 'Need a published preview', blockerReport: { blockedOn: 'permission', requestedActor: 'owner', requestedAction: 'Authorize PM checkpoint on integration for browser tests', evidence: 'Origin remains at the old SHA; fixes only exist in the registered worktree', diagnosticsAttempted: ['Compared origin SHA and worktree diff'], resumeCondition: 'The checkpoint authorization is recorded', reporterCanResolve: true } }, 'raise');
        assert.equal(raise.status, 'accepted', JSON.stringify(raise));
        const event = await db.activityLog.findFirstOrThrow({ where: { taskId: task.id, kind: 'task.blocker' }, orderBy: { createdAt: 'desc' } });
        const blocker = JSON.parse(event.payload!);
        assert.equal(blocker.permissionRequest.taskBranch, 'integration');
        assert.equal(blocker.permissionRequest.epicBranch, null, 'grant binds standalone target');
        const grant = await applyBlockerPermissionGrant({ taskId: task.id, projectId: project.id, actorUserId: owner.id, assigneeSlug: 'worker', blockerCommentId: blocker.commentId, permissionKind: 'publish_checkpoint', permissionScope: 'Publish CHK-1 for browser verification', authorizationBody: 'I hereby authorize PM to publish the checkpoint for CHK-1 to the standalone task branch integration for testing.' });
        assert.ok(grant.granted);
        const publish = await command('publish_checkpoint', { authorizationCommentId: grant.authorizationCommentId, comment: 'Publish for remaining live verification' }, 'publish');
        assert.equal(publish.status, 'accepted', JSON.stringify(publish));
        const result = await runEpicMergeSpoolJob({ kind: 'checkpoint', jobId: `checkpoint-${task.id}`, taskId: task.id, projectId: project.id, requestedByUserId: worker.id, requestedByUsername: 'worker', authorizationCommentId: grant.authorizationCommentId, note: 'Browser verification pending', enqueuedAt: new Date().toISOString() });
        assert.equal(result.outcome, 'published', JSON.stringify(result));
        const after = await db.task.findUniqueOrThrow({ where: { id: task.id }, include: { repositoryRun: true, checklist: true } });
        assert.equal(after.status, 'In Progress');
        assert.equal(after.repositoryRun?.baseSha, base, 'preserve full reviewer diff');
        assert.equal(after.repositoryRun?.candidateSha, null);
        assert.equal(after.checklist[0].completedAt, null);
        assert.equal(await db.reviewRun.count({ where: { taskId: task.id } }), 0);
        const repeat = await command('publish_checkpoint', { authorizationCommentId: grant.authorizationCommentId }, 'reuse');
        assert.notEqual(repeat.status, 'accepted', 'grant single-use');
        const completed = await db.activityLog.findFirstOrThrow({ where: { taskId: task.id, kind: 'pm.repo.checkpoint.ok' } });
        const receipt = JSON.parse(completed.payload!);
        assert.equal(receipt.epicBranch, null);
        assert.equal(receipt.publishedBranch, 'integration');
        assert.equal(receipt.publishedSha, await git(liveWt, 'rev-parse', 'HEAD'));
        assert.ok(taskToolActions({ status: 'In Progress', assignee: true, reviewer: false, canApprove: false, canFinish: false, unassigned: false, approved: true, epicChild: false, coding: true }).includes('publish_checkpoint'));
        console.log('PASS standalone checkpoint: exact feature push, replay preserves later edits, production/Epic guards, divergence refusal, owner grant + orchestrator + repository runner, incomplete verification retained and full review base preserved.');
    }
    finally {
        await db.$disconnect();
        await rm(root, { recursive: true, force: true });
    }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
