#!/usr/bin/env bash
# Set solid distinct colours per workspace, switching between a bright "day"
# palette and a muted coffee/pastel "night" palette.
#
# Optimised for low-latency workspace switching:
#   - tiny 16x16 PNGs (cheap to generate, instant to upload)
#   - every palette colour is preloaded into hyprpaper at startup, so a
#     workspace change is just a `hyprctl hyprpaper wallpaper` IPC call
#   - event-driven via Hyprland's socket2 (falls back to polling if socat
#     is unavailable or the socket can't be found)

set -euo pipefail

CACHE_DIR="$HOME/.cache/hyprpaper-solid"
CONF_PATH="$HOME/.config/hypr/hyprpaper.conf"
# Big enough to render cleanly on any monitor and avoid hyprpaper choking on
# tiny images, small enough that all 24 PNGs together cost <1MB on disk and
# negligible RAM once decoded.
PNG_SIZE=512
mkdir -p "$CACHE_DIR"

need() { command -v "$1" >/dev/null 2>&1 || { echo "Missing dependency: $1" >&2; exit 1; }; }
need hyprctl
need jq
need hyprpaper

MAGICK_BIN="$(command -v magick || command -v convert || true)"
[[ -n "$MAGICK_BIN" ]] || { echo "Missing dependency: magick/convert (ImageMagick)" >&2; exit 1; }

# === Palettes ================================================================
# Day palette — saturated brights.
PALETTE=(
  e6194b 3cb44b 4363d8 ffe119 f58231 911eb4
  46f0f0 f032e6 bcf60c 008080 800000 000075
)

# Night palette — dark, low-saturation pastels across the hue wheel.
NIGHT_PALETTE=(
  6b4148 6d4a3a 6b5832 4f6a4a 3a6a64 3d5a78
  5a4878 6a3e5e 4a3a30 3e5238 4a6878 6b3a3a
)

# Hours during which NIGHT_PALETTE is used: [NIGHT_START, 24) ∪ [0, NIGHT_END).
NIGHT_START=19
NIGHT_END=7

current_mode() {
  local h
  h=$((10#$(date +%H)))
  if (( h >= NIGHT_START || h < NIGHT_END )); then
    echo night
  else
    echo day
  fi
}

# === Image generation ========================================================
png_path() { echo "$CACHE_DIR/solid-${1}.png"; }

ensure_pngs() {
  local hex path
  for hex in "${PALETTE[@]}" "${NIGHT_PALETTE[@]}"; do
    path=$(png_path "$hex")
    [[ -f "$path" ]] || "$MAGICK_BIN" -size "${PNG_SIZE}x${PNG_SIZE}" xc:"#${hex}" PNG24:"$path"
  done
}

# Remove cache entries from older revisions of this script (different naming
# scheme or oversized PNGs), so the cache directory doesn't accumulate cruft.
prune_stale_cache() {
  find "$CACHE_DIR" -maxdepth 1 -type f -name 'ws-*.png' -delete 2>/dev/null || true
}

# === Palette lookup ==========================================================
hex_for_ws() {
  local ws="$1" mode="$2" n
  if [[ ! "$ws" =~ ^-?[0-9]+$ ]] || (( ws <= 0 )); then
    ws=1
  fi
  if [[ "$mode" == night ]]; then
    n=${#NIGHT_PALETTE[@]}
    echo "${NIGHT_PALETTE[$(( (ws - 1) % n ))]}"
  else
    n=${#PALETTE[@]}
    echo "${PALETTE[$(( (ws - 1) % n ))]}"
  fi
}

monitors_ws() {
  hyprctl monitors -j | jq -r '.[] | "\(.name) \(.activeWorkspace.id)"' | sort
}

# === Config (written once at startup) =======================================
# hyprpaper reads this on (re)start. Preloads every palette PNG so all
# subsequent switches are buffer swaps.
write_conf() {
  local mode mon wsid hex tmp p
  mode=$(current_mode)
  tmp="$(mktemp)"
  {
    echo "# Auto-generated by hyprpaper-solid-workspaces.sh"
    echo "splash = false"
    for p in "${PALETTE[@]}" "${NIGHT_PALETTE[@]}"; do
      echo "preload = $(png_path "$p")"
    done
    while read -r mon wsid; do
      hex=$(hex_for_ws "$wsid" "$mode")
      echo "wallpaper = ${mon},$(png_path "$hex")"
    done < <(monitors_ws)
  } > "$tmp"
  mv "$tmp" "$CONF_PATH"
}

# === Runtime apply ==========================================================
apply_all() {
  local mode mon wsid hex img rc=0
  mode=$(current_mode)
  while read -r mon wsid; do
    hex=$(hex_for_ws "$wsid" "$mode")
    img=$(png_path "$hex")
    hyprctl hyprpaper wallpaper "$mon,$img" >/dev/null 2>&1 || rc=1
  done < <(monitors_ws)
  return $rc
}

# === Hyprpaper lifecycle ====================================================
HYPRPAPER_LOG="${XDG_RUNTIME_DIR:-/tmp}/hyprpaper.log"

hyprpaper_alive() {
  # hyprpaper 0.8.x can accept wallpaper IPC while still rejecting newer
  # introspection requests like `listactive`, so process liveness is the most
  # compatible check here. `apply_all` verifies the actual wallpaper IPC path.
  pgrep -x hyprpaper >/dev/null 2>&1
}

start_hyprpaper() {
  if systemctl --user status hyprpaper.service >/dev/null 2>&1; then
    systemctl --user restart hyprpaper.service >/dev/null 2>&1 || true
  else
    pkill -x hyprpaper 2>/dev/null || true
    # detach so hyprpaper outlives this shell; capture log for diagnostics
    setsid -f hyprpaper >"$HYPRPAPER_LOG" 2>&1 </dev/null
  fi
}

# Restart hyprpaper if it's gone and wait for its IPC to come up.
ensure_hyprpaper() {
  hyprpaper_alive && return 0
  start_hyprpaper
  for _ in $(seq 1 40); do
    hyprpaper_alive && return 0
    sleep 0.1
  done
  return 1
}

# === Event loop =============================================================
SOCK="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/hypr/${HYPRLAND_INSTANCE_SIGNATURE:-}/.socket2.sock"

run_loop() {
  local last_state="" state mode combined line use_events=0
  if command -v socat >/dev/null 2>&1 && [[ -S "$SOCK" ]]; then
    use_events=1
  fi

  tick() {
    state=$(monitors_ws 2>/dev/null || true)
    [[ -z "$state" ]] && return
    mode=$(current_mode)
    combined="$mode|$state"
    [[ "$combined" == "$last_state" ]] && return
    # Revive hyprpaper if it died since last tick, then apply.
    # On IPC failure, leave last_state unchanged so the next tick retries.
    ensure_hyprpaper || return
    if apply_all; then
      last_state="$combined"
    fi
  }

  if (( use_events )); then
    # Event-driven. 60s read timeout doubles as a ticker for the day/night
    # boundary check, a hyprpaper liveness check, and a safety net against
    # any missed events.
    while read -t 60 -r line || (( $? > 128 )); do
      case "$line" in
        ''|workspace*|focusedmon*|monitor*|createworkspace*|destroyworkspace*) ;;
        *) continue ;;
      esac
      # Force a re-apply if hyprpaper died since last tick.
      hyprpaper_alive || last_state=""
      tick
    done < <(socat -u "UNIX-CONNECT:$SOCK" - 2>/dev/null)
    echo "hyprpaper-solid-workspaces: event stream closed; exiting" >&2
  else
    while true; do
      hyprpaper_alive || last_state=""
      tick
      sleep 0.5
    done
  fi
}

# === Main ===================================================================
prune_stale_cache
ensure_pngs
write_conf
start_hyprpaper

# Wait for hyprpaper IPC to come up by retrying the first apply.
for _ in $(seq 1 40); do
  apply_all && break
  sleep 0.1
done

run_loop
