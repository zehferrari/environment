#!/usr/bin/env bash
# Set one solid distinct colour per DISPLAY (monitor), not per workspace.
# - Generates ~/.config/hypr/hyprpaper.conf
# - Applies wallpapers via hyprctl hyprpaper
# - Re-applies if monitors are added/removed or connector names shuffle

set -euo pipefail

CACHE_DIR="$HOME/.cache/hyprpaper-solid"
CONF_PATH="$HOME/.config/hypr/hyprpaper.conf"
mkdir -p "$CACHE_DIR"

need() { command -v "$1" >/dev/null 2>&1 || { echo "Missing dependency: $1" >&2; exit 1; }; }
need hyprctl
need jq
need hyprpaper

# prefer ImageMagick v7 `magick`, fallback to `convert`
MAGICK_BIN="$(command -v magick || command -v convert || true)"
if [[ -z "$MAGICK_BIN" ]]; then
  echo "Missing dependency: magick/convert (ImageMagick)" >&2
  exit 1
fi

# Distinct palette (fallback).
PALETTE=(
  e6194b  # red
  3cb44b  # green
  4363d8  # blue
  ffe119  # yellow
  f58231  # orange
  911eb4  # purple
  46f0f0  # cyan
  f032e6  # magenta
  bcf60c  # lime
  008080  # teal
  800000  # maroon
  000075  # navy
)

monitors_json() {
  hyprctl monitors -j
}

# Monitor name and description pairs (sorted for stable comparisons)
# monitors_state() was used for a background watcher; no longer needed in one-shot mode.

# Assign a colour based on monitor *name* and description.
# This lets us distinguish between identical panels (e.g. two ZEUSLAPs on HDMI-A-2/3).
hex_for_monitor() {
  local mon="$1"
  local desc="$2"

  # Explicit per-output overrides first.
  if [[ "$mon" == "HDMI-A-2" ]]; then
    echo "f58231" # orange for new ZEUSLAP on HDMI-A-2
    return
  fi
  if [[ "$mon" == "HDMI-A-3" ]]; then
    echo "e6194b" # red for ZEUSLAP on HDMI-A-3
    return
  fi

  # Then fall back to description-based defaults.
  if [[ "$desc" == *"DELL U2421E"* ]]; then
    echo "4363d8" # blue
    return
  fi
  if [[ "$desc" == *"KAMN34FXQULA"* ]]; then
    echo "911eb4" # purple
    return
  fi
  if [[ "$desc" == *"KAMN27Q18CSA"* ]]; then
    echo "3cb44b" # green
    return
  fi
  if [[ "$desc" == *"M14t Gen2"* ]]; then
    echo "f58231" # orange (Lenovo, if present)
    return
  fi
  if [[ "$desc" == *"ZEUSLAP"* ]]; then
    echo "e6194b" # generic ZEUSLAP fallback (if not HDMI-A-2/3 for some reason)
    return
  fi

  # Fallback: pick from palette using a simple hash over the description.
  local sum=0 i c ord
  for ((i=0; i<${#desc}; i++)); do
    c=${desc:i:1}
    LC_CTYPE=C printf -v ord '%d' "'$c"
    sum=$(( (sum + ord) % 1048576 ))
  done
  local idx=$(( sum % ${#PALETTE[@]} ))
  echo "${PALETTE[$idx]}"
}

# Generate a filename-safe token from a description.
safe_token() {
  local s="$1"
  s=${s// /_}
  s=${s//\//_}
  s=${s//:/_}
  s=${s//[^A-Za-z0-9._-]/_}
  echo "$s"
}

img_for_monitor() {
  local mon="$1"
  local desc="$2"
  local hex
  hex=$(hex_for_monitor "$mon" "$desc")
  local token
  token=$(safe_token "$desc")

  local path="$CACHE_DIR/mon-${token}-${hex}.png"
  if [[ ! -f "$path" ]]; then
    "$MAGICK_BIN" -size 5120x3200 canvas:"#${hex}" "$path"
  fi
  echo "$path"
}

# NOTE: we no longer manage the hyprpaper process here.
# hyprpaper should be started once (e.g. via Hyprland exec-once or systemd user unit),
# and this script only updates its configuration and tells it which wallpapers to use.

write_conf() {
  local tmp
  tmp="$(mktemp)"
  {
    echo "# Auto-generated by hyprpaper-solid-displays.sh"
    echo "splash = false"

    monitors_json | jq -r '.[] | "\(.name)\t\(.description)"' | while IFS=$'\t' read -r mon desc; do
      img=$(img_for_monitor "$mon" "$desc")
      echo "preload = $img"
      echo "wallpaper = ${mon},$img"
    done
  } > "$tmp"
  mv "$tmp" "$CONF_PATH"
}

apply_all() {
  local rc=0
  monitors_json | jq -r '.[] | "\(.name)\t\(.description)"' | while IFS=$'\t' read -r mon desc; do
    img=$(img_for_monitor "$mon" "$desc")
    hyprctl hyprpaper preload "$img" >/dev/null 2>&1 || true
    if ! hyprctl hyprpaper wallpaper "$mon,$img" >/dev/null 2>&1; then
      rc=1
    fi
  done
  return "$rc"
}

# One-shot apply: generate config, ask running hyprpaper to apply wallpapers, then exit.
write_conf
for _ in $(seq 1 20); do
  apply_all && break
  sleep 0.2
done

exit 0
